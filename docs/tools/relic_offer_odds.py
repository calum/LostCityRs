#!/usr/bin/env python3
"""Monte Carlo odds that each relic is OFFERED at each task count (docs/reference/relic-offer-odds.md).

Usage: python3 docs/tools/relic_offer_odds.py [--games N] [--seed S] > docs/reference/relic-offer-odds.md

Reads the relic list from mods/relics/scripts/relic_offer.rs2 (relic_name cases, ids hidden by relic_exists, the
`$i <= N` loop bound), so a relic added there shows up when you rerun it. The rules it plays are the ones in that file:
- the pool is every relic that exists and is not owned; id 1 (XP Multiplier) is in the pool while its tier is below 3 and can be taken 3 times;
- an offer is 3 distinct relics drawn uniformly from the pool (the game's seeded generator is a uniform draw by index; not tested for bias);
- offer 0 is the first-login offer; after that, one offer per task done, count 1..TASKS (task count minus the retired task 37) (the finals 24/25 are treated as ordinary tasks,
  the real game gives them no offer when they are not the 10th);
- count 10: Quest Pass (id 2) is granted, no choice; Quest Pass is never in an ordinary offer;
- every 5th count (5, 10 if Quest Pass is already owned, 15, ...): the first option is the XP Multiplier if still available;
- the player picks one of the offered relics UNIFORMLY AT RANDOM (an assumption: real players choose, so real odds differ);
- picking Hoarder (19) opens a second offer drawn only from relics offered and declined before; the player picks uniformly again.
"Offered" = the relic is one of the options at that count. Hoarder's second offer is counted in the same row.
"""
import argparse, random, re, sys, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SRC = os.path.join(ROOT, 'mods', 'relics', 'scripts', 'relic_offer.rs2')
RETIRED_TASKS = 1  # task 37 is retired (never done)
TASKS = int(re.search(r'\^relic_task_count = (\d+)', open(os.path.join(ROOT, 'mods', 'relics', 'configs', 'relic.constant'), encoding='utf8').read()).group(1)) - RETIRED_TASKS  # tasks that can be done


def load():
    text = open(SRC, encoding='utf8').read()
    names = {int(i): n for i, n in re.findall(r'case (\d+) : return\("([^"]*)"\);', text.split('[proc,relic_desc]')[0])}
    hidden = {int(x) for x in re.findall(r'\$id = (\d+)', text.split('[proc,relic_exists]')[1].split('return(1)')[0])}
    top = int(re.search(r'while \(\$i <= (\d+)\)', text).group(1))
    ids = [i for i in range(1, top + 1) if i in names and i not in hidden]
    return names, ids


def play(rng, ids, counts, owned_counts, tier_max=3):
    owned, tier, declined = set(), 0, set()
    seen = set()  # (relic, count) already counted this game (Hoarder's second offer shares its count)

    def pool(excl, only_declined=False):
        out = []
        for i in ids:
            if i == 2 or i in excl:
                continue
            if i == 1:
                ok = tier < tier_max
            else:
                ok = i not in owned
            if ok and (not only_declined or i in declined):
                out.append(i)
        return out

    def grant(i):
        nonlocal tier
        if i == 1:
            tier += 1
        else:
            owned.add(i)
        declined.discard(i)

    def offer(count, force_xp, only_declined=False):
        shown = []
        if force_xp and 1 in pool(set()):
            shown.append(1)
        while len(shown) < 3:
            p = pool(set(shown), only_declined)
            if not p:
                break
            shown.append(rng.choice(p))
        if not shown:
            return
        for i in shown:
            if (i, count) not in seen:
                seen.add((i, count))
                counts[i][count] += 1
        pick = rng.choice(shown) if len(shown) > 1 else (rng.choice([shown[0], 0]))
        for i in shown:
            if i != pick:
                declined.add(i)
        if pick:
            grant(pick)
            if pick == 19 and not only_declined:
                offer(count, False, True)

    offer(0, False)
    for c in range(1, TASKS + 1):
        if c == 10 and 2 not in owned:
            owned.add(2)
            counts[2][c] += 1
            seen.add((2, c))
        else:
            offer(c, c % 5 == 0)
        for i in owned | ({1} if tier else set()):
            owned_counts[i][c] += 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--games', type=int, default=20000)
    ap.add_argument('--seed', type=int, default=1)
    a = ap.parse_args()
    names, ids = load()
    rng = random.Random(a.seed)
    counts = {i: [0] * (TASKS + 1) for i in ids}
    owned_counts = {i: [0] * (TASKS + 1) for i in ids}
    for _ in range(a.games):
        play(rng, ids, counts, owned_counts)
    n = a.games
    cols = [0] + [5, 10, 15, 20, 25, 30, 35, TASKS]
    allc = list(range(0, TASKS + 1))
    print('# Relic offer odds by task count (generated)\n')
    print(f'Generated by `docs/tools/relic_offer_odds.py` ({n} simulated games, seed {a.seed}) from `mods/relics/scripts/relic_offer.rs2`. Rules and assumptions are in the script header: the main one is that the simulated player picks one of the three offered relics **at random**; a real player chooses, so real odds will differ.\n')
    print('Each cell is the chance (%) that the relic is one of the options at that task count (0 = the first-login offer).\n')
    show = [0] + list(range(1, TASKS + 1))
    picks = len(ids) - 2 + 3
    print(f'There are {len(ids)} relics (ids that exist today); offers can give {picks} picks (the XP Multiplier counts 3 times; Quest Pass is not in offers), plus Quest Pass at count 10. With one pick per offer the pool is empty after about {picks} picks, so late counts (roughly 30 and up) have no offer: this is why the late columns read 0.\n')
    print('## Chance the relic is offered, selected counts\n')
    print('| Relic | ' + ' | '.join(str(c) for c in cols) + ' |')
    print('|---|' + '---|' * len(cols))
    for i in ids:
        print(f'| {i} {names[i]} | ' + ' | '.join(f'{100 * counts[i][c] / n:.0f}' for c in cols) + ' |')
    print('\n(Quest Pass is 100 at count 10 only. XP Multiplier is 100 at counts 5, 15, 25, 35 while a tier is left.)\n')
    print('## Chance the relic is offered, every task count\n')
    print('| Relic | ' + ' | '.join(str(c) for c in allc) + ' |')
    print('|---|' + '---|' * len(allc))
    for i in ids:
        print(f'| {i} {names[i]} | ' + ' | '.join(f'{100 * counts[i][c] / n:.0f}' for c in allc) + ' |')
    print('\n## Chance the relic is owned after the Nth task\n')
    print('| Relic | ' + ' | '.join(str(c) for c in cols[1:]) + ' |')
    print('|---|' + '---|' * (len(cols) - 1))
    for i in ids:
        print(f'| {i} {names[i]} | ' + ' | '.join(f'{100 * owned_counts[i][c] / n:.0f}' for c in cols[1:]) + ' |')


main()
